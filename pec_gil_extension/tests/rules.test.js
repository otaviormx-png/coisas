const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const rules=require('../rules.js');
const record={sourceKey:'1',professional:'Raul Pimentel Kastrup',patientName:'Paciente Teste',birthDate:'01/02/1980',attendanceDate:'21/09/2026',sex:'F',attendanceStatus:'Aguardando atendimento',gilSelected:true};
