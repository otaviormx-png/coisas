assert.equal(rules.normalizeBatch({...batch,records:[record,{...record,professional:'Monica'}]}).records.length,1);
assert.throws(()=>rules.normalizeBatch({...batch,records:[{...record,professional:'Monica'}]}),/Selecione o Raul/);
assert.equal(rules.exportPayload(batch).records[0].sex,'2');
